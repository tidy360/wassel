type Lang = keyof typeof dict;
type Key = keyof typeof dict["ar"];

const LangContext = createContext<{ lang: Lang; t: (k: Key) => string; toggle: () => void }>({
  lang: "ar",
  t: (k) => dict.ar[k],
  toggle: () => {},
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>((localStorage.getItem("cashiri_lang") as Lang) || "ar");

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    localStorage.setItem("cashiri_lang", lang);
  }, [lang]);

  const t = (k: Key) => dict[lang][k];
  const toggle = () => setLang((l) => (l === "ar" ? "en" : "ar"));

  return <LangContext.Provider value={{ lang, t, toggle }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
